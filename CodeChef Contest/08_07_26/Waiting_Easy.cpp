void marwan() {
    int n;
    cin >> n;
    vector<int> v(n);
    for (auto &vl : v)
        cin >> vl;
    int mn = 0, ans = 0ll;
    for (int i = 0; i < n; i++) {
        if (mn > v[i])
            ans += mn - v[i];
        mn = max(mn, v[i]);
    }
    cout << ans << endl;
}
