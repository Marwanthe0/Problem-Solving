void marwan() {
  int n;
  cin >> n;
  vector<int> v(n);
  int eve = 0, odd = 0;
  for (auto &vl : v) {
    cin >> vl;
    if (vl & 1)
      odd++;
    else
      eve++;
  }
  if (odd == eve)
    cout << odd * 2 << endl;
  else
    cout << min(odd, eve) * 2 + 1 << endl;
}
