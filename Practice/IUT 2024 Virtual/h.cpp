void marwan() {
    string s;
    cin >> s;
    auto f = [&](char c) {
        if (c == 'z')
            return 'a';
        else if (c == 'Z')
            return 'A';
        else
            return ++c;
    };
    for (int i = 0; i < s.size(); i++) {
        cout << f(s[i]);
    }
    cout << endl;
}
