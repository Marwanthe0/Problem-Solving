void marwan() {
    int n, t, nk, s;
    cin >> n >> t >> nk >> s;
    int ans = (n / (t + nk)) + (n % (t + nk) != 0);
    int sp = 10 * nk;
    n -= s * t;
    ans = min(ans, s + (n / (t + sp) + (n % (t + sp) != 0)));
    cout << ans << endl;
}
