void marwan() {
  int n;
  cin >> n;
  int sum = 0;
  while (n > 9) {
    while (n) {
      sum += n % 10;
      n /= 10;
    }
    n = sum;
    sum = 0;
  }
  if (n == 9)
    cout << 1 << endl;
  else
    cout << n + 1 << endl;
}
